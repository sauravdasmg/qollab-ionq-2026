"""Regenerate the flat Qollab evidence module; no simulations are run."""
import hashlib
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]


def render(source):
    raw = source.read_bytes()
    data = json.loads(raw)
    hashes = {'summary.json': hashlib.sha256(raw).hexdigest()}
    for suite, content in data['suites'].items():
        hashes[suite + '.json'] = content['source_sha256']
    return ('"""Generated by experiments/make_curves.py; do not edit.\n'
            'LOCAL MODEL (calibrated IonQ-like channel, frozen n=24, fresh n=24).\n'
            'W is DETERMINISTIC with calibration sensitivity, not a sampling CI.\n'
            'N uses 97.5% instance-bootstrap simultaneous bands.\n"""\n'
            + 'LABEL = "LOCAL MODEL (calibrated IonQ-like channel, frozen n=24, fresh n=24)"\n'
            + 'N_INSTANCES = {"frozen": 24, "fresh": 24}\n'
            + 'SOURCE_SHA256 = ' + pprint.pformat(hashes, sort_dicts=True) + '\n'
            + 'CURVES = ' + pprint.pformat(data, sort_dicts=True, width=110) + '\n')


def main():
    target = ROOT / 'nt_curves.py'
    content = render(ROOT / 'results' / 'summary.json')
    if len(content.encode('utf-8')) >= 2_000_000:
        raise ValueError('Qollab file size limit exceeded')
    target.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
